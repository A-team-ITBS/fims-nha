-- The ledger of Budget Revisions: one row = one budget line (fims.budget_line_items) changed by one APPROVED budget revision / realignment.
--
-- Approving a revision used to move budget_line_items.suggested_amount (and adjustment) in place, so a line's history was lost and
-- suggested_amount stopped being "what FMD suggested". Now suggested_amount is left alone and the approval writes here instead:
--   * a REVISION writes one row for its From line:        amount = To Amount − the line's current balance (signed)
--   * a REALIGNMENT writes two rows — the From line (REALIGNMENT_OUT, negative) and the To line (REALIGNMENT_IN, positive) — of the same size
-- A line's Revision Amount is SUM(amount) over its rows; the COB Monitoring sheet's Revision Amount column reads exactly that (BudgetLineBalanceSql::revisionExpr()),
-- and the line's current balance is suggested_amount + SUM(amount) (BudgetLineBalanceSql::revisedExpr()).
-- budget_line_items.adjustment is that sum, kept in the table by triggers on this one, and each row also carries the line's running adjustment in its own `adjustment`
-- column (both: "03 - alter_table/53 - budget_line_item_revision_transaction_adjustment.sql"); revised_amount is generated by the line table (54).
--
-- transaction_type: REVISION | REALIGNMENT_OUT | REALIGNMENT_IN — the three an approval writes; LEGACY — written once by
-- "03 - alter_table/52 - budget_line_item_revision_transaction_backfill.sql" for what was approved before this table existed (no budget_revision_id).

-- A database that already has the table under its first name, fims.budget_line_item_transaction, gets it RENAMED here (with its sequence,
-- constraints and indexes — their rows are kept) instead of a second, empty table being created beside it. A fresh database skips this block.
DO $$
DECLARE
    obj TEXT;
BEGIN
    IF to_regclass('fims.budget_line_item_transaction') IS NOT NULL AND to_regclass('fims.budget_line_item_revision_transaction') IS NULL THEN
        ALTER TABLE fims.budget_line_item_transaction RENAME TO budget_line_item_revision_transaction;
        IF to_regclass('fims.budget_line_item_transaction_transaction_id_seq') IS NOT NULL THEN
            ALTER SEQUENCE fims.budget_line_item_transaction_transaction_id_seq RENAME TO budget_line_item_revision_transaction_transaction_id_seq;
        END IF;
        -- constraints first (renaming the primary key renames its index too), then the plain indexes
        FOR obj IN SELECT conname FROM pg_constraint
                   WHERE conrelid = 'fims.budget_line_item_revision_transaction'::regclass AND conname LIKE '%budget_line_item_transaction%' LOOP
            EXECUTE format('ALTER TABLE fims.budget_line_item_revision_transaction RENAME CONSTRAINT %I TO %I',
                           obj, replace(obj, 'budget_line_item_transaction', 'budget_line_item_revision_transaction'));
        END LOOP;
        FOR obj IN SELECT indexname FROM pg_indexes
                   WHERE schemaname = 'fims' AND tablename = 'budget_line_item_revision_transaction' AND indexname LIKE '%budget_line_item_transaction%' LOOP
            EXECUTE format('ALTER INDEX fims.%I RENAME TO %I', obj, replace(obj, 'budget_line_item_transaction', 'budget_line_item_revision_transaction'));
        END LOOP;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS fims.budget_line_item_revision_transaction (
    transaction_id      SERIAL PRIMARY KEY,
    budget_revision_id  INTEGER,
    budget_line_item_id INTEGER NOT NULL,
    transaction_type    VARCHAR(20) NOT NULL,
    previous_amount     NUMERIC(18,2) NOT NULL,
    amount              NUMERIC(18,2) NOT NULL,
    new_amount          NUMERIC(18,2) NOT NULL,
    created_by          INTEGER,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_budget_line_item_revision_transaction_revision FOREIGN KEY (budget_revision_id)
        REFERENCES fims.budget_revision(id),
    CONSTRAINT fk_budget_line_item_revision_transaction_line_item FOREIGN KEY (budget_line_item_id)
        REFERENCES fims.budget_line_items(budget_line_item_id) ON DELETE CASCADE,
    CONSTRAINT chk_budget_line_item_revision_transaction_type CHECK (transaction_type IN ('REVISION', 'REALIGNMENT_OUT', 'REALIGNMENT_IN', 'LEGACY')),
    CONSTRAINT chk_budget_line_item_revision_transaction_new CHECK (new_amount = previous_amount + amount)
);

COMMENT ON TABLE fims.budget_line_item_revision_transaction IS 'Ledger of approved Budget Revisions / Realignments: one row per budget line a request changed. SUM(amount) per line is its Revision Amount (COB Monitoring); suggested_amount itself is never changed by a revision.';
COMMENT ON COLUMN fims.budget_line_item_revision_transaction.budget_revision_id IS 'The approved fims.budget_revision this row belongs to. NULL only for LEGACY rows (approved before this table existed).';
COMMENT ON COLUMN fims.budget_line_item_revision_transaction.transaction_type IS 'REVISION = the From line of a revision; REALIGNMENT_OUT / REALIGNMENT_IN = the From / To line of a realignment; LEGACY = the net of what was approved before this ledger existed.';
COMMENT ON COLUMN fims.budget_line_item_revision_transaction.previous_amount IS 'The line''s current balance just before this transaction: its revised amount (suggested_amount + its earlier transactions) less what approved CBAs / CFAs hold and RFAs / LAAs have drawn (the remaining balance). (A LEGACY row: the amount without the legacy net.)';
COMMENT ON COLUMN fims.budget_line_item_revision_transaction.amount IS 'The signed change this transaction made to the line: a decrease or a realignment out is negative.';
COMMENT ON COLUMN fims.budget_line_item_revision_transaction.new_amount IS 'The line''s current balance just after this transaction (previous_amount + amount).';
COMMENT ON COLUMN fims.budget_line_item_revision_transaction.created_by IS 'uac.users.user_id of who approved the request (-1 = the built-in administrator; NULL for LEGACY rows).';

-- one row per line per request: a request can never be applied to the same line twice
CREATE UNIQUE INDEX IF NOT EXISTS uq_budget_line_item_revision_transaction_revision_line
    ON fims.budget_line_item_revision_transaction (budget_revision_id, budget_line_item_id) WHERE budget_revision_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_budget_line_item_revision_transaction_line_item ON fims.budget_line_item_revision_transaction (budget_line_item_id);
