<?php

namespace PHPMaker2024\FIMS\Service;

use PHPMaker2024\FIMS as App;

/**
 * Budget revisions: a request to change a BUDGET LINE's amount — a chart-of-accounts line item of a budget request
 * (fims.budget_line_items) — optionally moving the difference to a second budget line (the To line).
 *
 * A line's CURRENT amount is its REMAINING BALANCE — the figure the form shows as "Current balance" and the COB shows as Remaining Balance:
 *   revised amount (suggested_amount, Budget Processing's figure — STABLE, nothing ever moves it — plus the line's Revision Amount, the sum of its rows in the
 *   ledger fims.budget_line_item_revision_transaction)  LESS what approved CBAs / CFAs hold against it and what RFAs / LAAs have drawn from them
 *   (the earmark table; BudgetLineBalanceSql::correlatedAvailableExpr()). A New Amount on a request is therefore the line's new remaining balance.
 * Approving a revision writes the ledger — one row per line, with the signed amount, the previous balance and the new balance — and nothing else of
 * substance; proposed_amount and suggested_amount are never touched:
 *   From line  ledger amount = to_amount − its current balance                    → its balance becomes to_amount
 *   To line    ledger amount = the From line's current balance − to_amount        → it receives the difference
 * so a transfer deducts from one line and adds to the other by the same amount. A line's Revision Amount is the total of those amounts, whatever the
 * balance was when each was written. Each ledger row also carries the line's running `adjustment` (the earlier total plus its amount), and the line's own `adjustment` is that total — both set by triggers on the ledger (03 - alter_table/53), so approving only INSERTS the ledger row. (revised_amount is generated by the table — suggested_amount + adjustment, 03 - alter_table/54. There is no stored
 * stored revised amount to keep in step: it is always suggested_amount + the ledger total, and the table's generated revised_amount column says the same.)
 * The COB Monitoring sheet's Revision Amount is the sum of the ledger rows (BudgetLineBalanceSql::revisionExpr()).
 * A revision that would take the From line's balance below zero is refused — which also keeps its revised amount from going below what is held
 * against it — when it is filed, when it is edited and again when it is approved (fromBalanceError()); an increase is never refused.
 * See _assets/sql/01 - fims/03 - alter_table/23 - budget_revision_on_budget_reference_number.sql.
 *
 * Status flow:  Saved  --process()-->  Submitted  --review()-->  Approved | Declined
 *   create() files a request as SAVED; only a Saved request can be edited (update()). process() submits it — from then on it cannot be
 *   edited — and only a Submitted request can be reviewed (approved or declined) by FMD. The same checks as at filing are made again when
 *   it is processed and when it is approved, because the lines can change in between.
 *
 * Two kinds of request, stored in fims.budget_revision.request_type (03 - alter_table/42):
 *   REVISION     — no To line: the From line's amount simply changes.
 *   REALIGNMENT  — a To line: funds MOVE from the From line to the To line, and both lines must be in the SAME FISCAL YEAR
 *                  (sameYearError(): refused when it is filed or edited, and when it is approved).
 * The type always follows the To line — it is written with the request (typeFor()) and rewritten whenever the To line is edited, so
 * the two can never disagree. A client may also send `request_type` when it files / edits a request to say which one it means; it is
 * then held to it (a realignment needs its To line, a revision cannot have one — see typeError()).
 * (03 - alter_table/42 also dropped the legacy from_budget_req_id / to_budget_req_id columns.)
 */
class BudgetRevisionService
{
    // The statuses live in fims.settings_status (status_for = 'budget_revision'), looked up by NAME — their ids differ per
    // install (see statusId()). status_id is NOT NULL and is not on the form, so a newly filed revision starts as Saved (it can still
    // be edited); process() then Submits it (no more editing — it is in front of FMD), and review() moves it to Approved or Declined.
    // Seeded by "_assets/sql/01 - fims/04 - seed_data/08 - budget_revision_statuses.sql" (which also renames the old 'Pending' to 'Submitted').
    private const STATUS_FOR       = 'budget_revision';
    private const STATUS_SAVED     = 'Saved';
    private const STATUS_SUBMITTED = 'Submitted';
    private const STATUS_APPROVED  = 'Approved';
    private const STATUS_DECLINED  = 'Declined';

    /** @var array<string, int> status name => id, read once per request */
    private array $statusIds = [];

    // A line's current amount is kept below 10^13 (proposed_amount is NUMERIC(15,2)).
    private const MAX_LINE_AMOUNT = 10000000000000;

    private string $table          = 'fims.budget_revision';
    private string $tableLines     = 'fims.budget_line_items';
    private string $tableReq       = 'fims.budget_req';
    private string $tableReqProj   = 'fims.budget_req_project';
    private string $tableReqProg   = 'fims.budget_req_program';
    private string $tableProgram   = 'fims.program';
    private string $tableProject   = 'fims.project';
    private string $tableAccounts  = 'fims.chart_of_accounts';
    private string $tableRc        = 'fims.responsibility_code';
    private string $tableStatus    = 'fims.settings_status';
    private string $tableUser      = 'uac.users';

    // The JOINs that turn a revision's line id (rv.$col) into the line and everything shown with it, under the alias prefix $p:
    // {p}l the line, {p}b its budget request (+ {p}rc its office, {p}st its status), {p}bp its project (+ {p}bg its program row,
    // {p}pg / {p}pj their names), {p}coa its account. All LEFT JOINs: a line that no longer exists leaves everything NULL.
    private function lineJoins(string $p, string $col): string
    {
        return "LEFT JOIN {$this->tableLines} {$p}l ON {$p}l.budget_line_item_id = rv.{$col}
                LEFT JOIN {$this->tableReq} {$p}b ON {$p}b.budget_reference_number = {$p}l.budget_reference_number
                LEFT JOIN {$this->tableRc} {$p}rc ON {$p}rc.rc_id = {$p}b.rc_id
                LEFT JOIN {$this->tableStatus} {$p}st ON {$p}st.id = {$p}b.status_id
                LEFT JOIN {$this->tableReqProj} {$p}bp ON {$p}bp.budget_req_project_id = {$p}l.budget_req_project_id
                LEFT JOIN {$this->tableReqProg} {$p}bg ON {$p}bg.budget_req_program_id = {$p}bp.budget_req_program_id
                LEFT JOIN {$this->tableProgram} {$p}pg ON {$p}pg.program_code = {$p}bg.program_code
                LEFT JOIN {$this->tableProject} {$p}pj ON {$p}pj.project_code = {$p}bp.project_code
                LEFT JOIN {$this->tableAccounts} {$p}coa ON {$p}coa.account_id = {$p}l.account_id";
    }

    // The columns of one line, named with the prefix $pre ('' for the From line, 'to_' for the To line).
    private function lineSelect(string $p, string $pre): string
    {
        return "{$p}b.budget_reference_number AS {$pre}budget_reference_number, {$p}b.fiscal_yr AS {$pre}fiscal_yr,
                       {$p}rc.rc_code AS {$pre}rc_code, {$p}rc.rc_name AS {$pre}rc_name,
                       {$p}st.name AS {$pre}budget_req_status_name, {$p}st.color AS {$pre}budget_req_status_color,
                       {$p}bg.program_code AS {$pre}program_code, {$p}pg.program_name AS {$pre}program_name,
                       {$p}bp.project_code AS {$pre}project_code, {$p}pj.project_name AS {$pre}project_name,
                       {$p}l.account_id AS {$pre}account_id, {$p}coa.account_code AS {$pre}account_code,
                       {$p}coa.account_title AS {$pre}account_title, {$p}l.particulars AS {$pre}particulars,
                       {$p}l.proposed_amount AS {$pre}proposed_amount, {$p}l.suggested_amount AS {$pre}suggested_amount,
                       " . BudgetLineBalanceSql::latestExpr($p . 'l') . " AS {$pre}line_latest,
                       " . BudgetLineBalanceSql::revisionExpr($p . 'l') . " AS {$pre}line_adjustment,
                       " . BudgetLineBalanceSql::revisedExpr($p . 'l') . " AS {$pre}line_revised,
                       " . BudgetLineBalanceSql::heldExpr($p . 'l') . " AS {$pre}line_held,
                       " . BudgetLineBalanceSql::correlatedAvailableExpr($p . 'l') . " AS {$pre}line_amount";
        // line_latest = the line's LATEST adjustment (the amount of its last ledger row — negative on the From line of a realignment, positive on the To line);
        // line_adjustment = the line's Revision Amount, summed from the ledger; line_revised = suggested_amount + that; line_held = what CBAs / CFAs hold and RFAs /
        // LAAs have drawn (the earmark table); line_amount = its CURRENT amount, the remaining balance = line_revised - line_held
    }

    // FROM + JOIN part shared by the list, count, sum and read queries.
    // fl… = the From line (from_budget_line_item_id) and what hangs off it; tl… = the optional To line.
    private function joinSql(): string
    {
        // rs = the REVISION's own status. Matched on status_for too, so a status_id that still holds an old number (the seed was not
        // run yet) is not read as some other module's status.
        return "FROM {$this->table} rv
                LEFT JOIN {$this->tableStatus} rs ON rs.id = rv.status_id AND rs.status_for = " . App\QuotedValue(self::STATUS_FOR, App\DataType::STRING, 'DB') . "
                " . $this->lineJoins('f', 'from_budget_line_item_id') . "
                " . $this->lineJoins('t', 'to_budget_line_item_id') . "
                LEFT JOIN {$this->tableUser} us ON us.user_id = rv.user_id";
    }

    // `status` is the readable form of the status — its name in capitals: SAVED / SUBMITTED / APPROVED / DECLINED, or UNKNOWN when status_id
    // matches no revision status — and status_name / status_color are the settings_status row itself (the page paints its badge
    // with that colour); requested_by_* is who filed it
    // (both NULL for the built-in administrator, whose user_id -1 has no users row).
    // The From line comes back as budget_reference_number / fiscal_yr / rc_* / budget_req_status_* (its request), program_* / project_*,
    // account_* / particulars, proposed_amount / line_adjustment / line_amount (its CURRENT amount); the To line (all NULL when
    // there is none) as the to_* equivalents. A line that no longer exists leaves its fields NULL — the revision still lists.
    private function selectSql(): string
    {
        return "SELECT rv.*,
                       " . $this->lineSelect('f', '') . ",
                       " . $this->lineSelect('t', 'to_') . ",
                       COALESCE(UPPER(rs.name), 'UNKNOWN') AS status, rs.name AS status_name, rs.color AS status_color,
                       us.username AS requested_by_username,
                       NULLIF(TRIM(CONCAT_WS(' ', us.first_name, us.last_name)), '') AS requested_by_name "
            . $this->joinSql();
    }

    // The id of the revision status called $name (Saved / Submitted / Approved / Declined), or null when it is not set up — the seed was not run.
    private function statusId(string $name): ?int
    {
        if (!array_key_exists($name, $this->statusIds)) {
            $row = App\ExecuteRow(
                "SELECT id FROM {$this->tableStatus} WHERE status_for = " . App\QuotedValue(self::STATUS_FOR, App\DataType::STRING, 'DB')
                . ' AND name = ' . App\QuotedValue($name, App\DataType::STRING, 'DB'),
                'DB'
            );
            if (!isset($row['id'])) {
                return null;   // not cached: a status added after this is picked up on the next call
            }
            $this->statusIds[$name] = (int) $row['id'];
        }

        return $this->statusIds[$name];
    }

    // The response for a status that is not set up: say what to run, change nothing.
    private function missingStatus(string $name): array
    {
        return ['success' => false, 'message' => "The status \"{$name}\" is not set up in the database yet, so nothing was changed. "
            . 'Run "_assets/sql/01 - fims/04 - seed_data/08 - budget_revision_statuses.sql" on the database '
            . '(or ask an administrator to run the SQL installer: node install_system.js --sql-only), then try again.'];
    }

    private function lineExists(int $id): bool
    {
        return (int) App\ExecuteScalar(
            "SELECT COUNT(*) FROM {$this->tableLines} WHERE budget_line_item_id = " . App\QuotedValue($id, App\DataType::NUMBER, 'DB'),
            'DB'
        ) > 0;
    }

    // The CURRENT amount of one line: its remaining balance — its revised amount (suggested_amount plus its Revision Amount from the ledger) less what CBAs / CFAs hold
    // and RFAs / LAAs have drawn — the "Current balance" the form shows.
    private function currentAmountOf(int $id): float
    {
        return round((float) App\ExecuteScalar(
            'SELECT ' . BudgetLineBalanceSql::correlatedAvailableExpr('l') . " FROM {$this->tableLines} l WHERE l.budget_line_item_id = "
            . App\QuotedValue($id, App\DataType::NUMBER, 'DB'),
            'DB'
        ), 2);
    }

    private function isAmount(mixed $value): bool
    {
        return is_numeric($value) && (float) $value >= 0;
    }

    // A budget line id: null when none was sent (null / ''), false when what was sent is not a usable id, otherwise the id.
    private function parseId(mixed $raw): int|null|false
    {
        if ($raw === null || $raw === '') {
            return null;
        }
        $id = filter_var($raw, FILTER_VALIDATE_INT);

        return ($id === false || $id <= 0) ? false : $id;
    }

    // The request_type a request with this To line has: no To line = a REVISION, a To line = a REALIGNMENT.
    private function typeFor(?int $toId): string
    {
        return $toId === null ? 'REVISION' : 'REALIGNMENT';
    }

    // The kind of request the client says it is filing (`request_type`, optional): REVISION or REALIGNMENT. When it is sent it must
    // agree with the To line — a realignment needs one, a revision cannot have one. Left out, nothing is held to it (the type is
    // then simply worked out from the To line). Returns an error message, or null when it fits.
    private function typeError(mixed $requested, ?int $toId): ?string
    {
        if ($requested === null || $requested === '') {
            return null;
        }
        $type = strtoupper(trim((string) $requested));
        if ($type === 'REALIGNMENT' && $toId === null) {
            return 'A realignment needs a To budget line (to_budget_line_item_id).';
        }
        if ($type === 'REVISION' && $toId !== null) {
            return 'A revision cannot have a To budget line — file a realignment to move funds to another budget line.';
        }
        if ($type !== 'REVISION' && $type !== 'REALIGNMENT') {
            return 'request_type must be REVISION or REALIGNMENT.';
        }

        return null;
    }

    // The fiscal year of a budget line: its budget request's fiscal_yr (null when the line, or its request, no longer exists).
    private function fiscalYearOf(int $lineId): ?int
    {
        $year = App\ExecuteScalar(
            "SELECT b.fiscal_yr FROM {$this->tableLines} l
               JOIN {$this->tableReq} b ON b.budget_reference_number = l.budget_reference_number
              WHERE l.budget_line_item_id = " . App\QuotedValue($lineId, App\DataType::NUMBER, 'DB'),
            'DB'
        );

        return ($year === null || $year === false || $year === '') ? null : (int) $year;
    }

    // A realignment stays inside one fiscal year: funds cannot be moved to a budget line of another year's budget. Returns an error
    // message, or null when the two lines are in the same year (or a year is unknown — a line that no longer exists is reported on its own).
    private function sameYearError(int $fromId, int $toId): ?string
    {
        $from = $this->fiscalYearOf($fromId);
        $to   = $this->fiscalYearOf($toId);
        if ($from !== null && $to !== null && $from !== $to) {
            return "Funds can only be moved between budget lines of the same fiscal year — the From budget line is in FY {$from}, the To budget line in FY {$to}.";
        }

        return null;
    }

    // The To line must be a different budget line ITEM, not merely a different row: two lines of the same budget request that sit in the same project and have the same
    // account are the same item (they differ only in their particulars), and moving funds between them changes nothing real. The same line is the same item too.
    // Returns an error message, or null when they are different items (or a line cannot be read — a missing line is reported on its own).
    private function sameItemError(int $fromId, int $toId): ?string
    {
        $rows = App\ExecuteRows(
            "SELECT budget_line_item_id, budget_reference_number, budget_req_project_id, account_id FROM {$this->tableLines} WHERE budget_line_item_id IN ({$fromId}, {$toId})",
            'DB'
        ) ?: [];
        if ($fromId === $toId || count($rows) < 2) {
            return null;   // the same-line case has its own message (transferError()); a missing line too
        }

        $same = (string) $rows[0]['budget_reference_number'] === (string) $rows[1]['budget_reference_number']
            && (string) ($rows[0]['budget_req_project_id'] ?? '') === (string) ($rows[1]['budget_req_project_id'] ?? '')
            && (string) ($rows[0]['account_id'] ?? '') === (string) ($rows[1]['account_id'] ?? '')
            && (string) ($rows[0]['account_id'] ?? '') !== '';

        return $same
            ? 'The To budget line is the same budget line item as the From budget line — the same account in the same project of the same budget request. Choose a different budget line item to move the funds to.'
            : null;
    }

    // A revision with a To line MOVES funds: the From line goes down to To Amount and the To line goes up by the difference.
    // So the To line must exist, be a different line IN THE SAME FISCAL YEAR, and To Amount must be lower than From Amount (an increase
    // would mean taking funds out of the To line). Returns an error message, or null when the combination is fine.
    private function transferError(int $fromId, int $toId, mixed $fromAmount, mixed $toAmount): ?string
    {
        if ($toId === $fromId) {
            return 'to_budget_line_item_id must be different from from_budget_line_item_id.';
        }
        if (!$this->lineExists($toId)) {
            return 'to_budget_line_item_id does not exist.';
        }
        $yearError = $this->sameYearError($fromId, $toId);
        if ($yearError !== null) {
            return $yearError;
        }
        $itemError = $this->sameItemError($fromId, $toId);
        if ($itemError !== null) {
            return $itemError;
        }
        if (round((float) $toAmount, 2) >= round((float) $fromAmount, 2)) {
            return 'To Amount must be lower than From Amount to move funds to the To budget line.';
        }

        return null;
    }

    // The From line's remaining balance must not end up negative. A New Amount is the line's new remaining balance (revised amount less what CBAs / CFAs hold and
    // RFAs / LAAs have drawn), so it may go down as far as zero and no further — which is also what stops the revised amount dropping below what is held. An
    // increase, or a decrease that fits, is always fine. $fromId is the line the revision is filed against (the check only needs the amount, but every caller
    // already passes both). Returns an error message, or null when the revision is fine.
    private function fromBalanceError(int $fromId, mixed $toAmount): ?string
    {
        $newAmount = round((float) $toAmount, 2);
        if ($newAmount >= 0) {
            return null;
        }

        return 'The From budget line cannot go below zero — To Amount ' . number_format($newAmount, 2) . ' would leave its remaining balance negative.';
    }

    // reason is optional long text — empty string is stored as NULL.
    // Quoted through the connection rather than App\QuotedValue(): that helper turns
    // line breaks and backslashes into literal "\n" / "\\" text, which PostgreSQL
    // would store as-is and corrupt a multi-line reason.
    private function reasonSql(array $body): string
    {
        $reason = trim((string) ($body['reason'] ?? ''));

        return $reason === '' ? 'NULL' : App\Conn('DB')->quote($reason);
    }

    // A failed statement, as the response. A database that has not had the revision migrations yet fails in a recognisable way —
    // the from_ / to_budget_line_item_id columns (23) or request_type (42) do not exist — and for that the message says what to run; the
    // database's own message is kept after it.
    private function failure(\Throwable $e): array
    {
        $message = $e->getMessage();
        if (preg_match('/budget_line_item_revision_transaction.{0,80}does not exist/is', $message)) {
            // a revision's lines read their current amount from the ledger, and an approval writes to it
            $message = 'Budget revisions now keep their transactions in the fims.budget_line_item_revision_transaction table, which has not been created in this database yet. Run '
                . '"_assets/sql/01 - fims/01 - table/50 - fims_budget_line_item_revision_transaction.sql" and then '
                . '"_assets/sql/01 - fims/03 - alter_table/52 - budget_line_item_revision_transaction_backfill.sql" (or node install_system.js --sql-only), then reload. '
                . '(' . $message . ')';
        } elseif (preg_match('/request_type.{0,80}does not exist/is', $message)) {
            $message = 'Budget revisions need a database update that has not been applied yet. Run '
                . '"_assets/sql/01 - fims/03 - alter_table/42 - budget_revision_add_request_type_drop_legacy_req_ids.sql" on the database, then reload. '
                . '(' . $message . ')';
        } elseif (preg_match('/_budget_line_item_id.{0,80}does not exist/is', $message)) {
            $message = 'Budget revisions need a database update that has not been applied yet. Run '
                . '"_assets/sql/01 - fims/03 - alter_table/23 - budget_revision_on_budget_reference_number.sql" on the database, then reload. '
                . '(' . $message . ')';
        }

        return ['success' => false, 'message' => $message];
    }

    // $budgetReference: a budget reference number ("BP-001") — the list keeps the revisions that touch a line of that budget request,
    // as the From line or the To line.
    public function fetchAlls(?int $page = null, int $limit = 10, string $fiscalYr = '', string $budgetReference = ''): array
    {
        try {
            $where = ['rv.deleted_at IS NULL'];

            if ($fiscalYr !== '') {
                $where[] = 'fb.fiscal_yr = ' . (int) $fiscalYr;
            }
            if (trim($budgetReference) !== '') {
                // a revision touches both of its lines, so it belongs to either one's budget request
                $ref     = App\QuotedValue(trim($budgetReference), App\DataType::STRING, 'DB');
                $where[] = "(fl.budget_reference_number = {$ref} OR tl.budget_reference_number = {$ref})";
            }
            $whereSql = implode(' AND ', $where);

            if ($page === null) {
                $data = App\ExecuteRows($this->selectSql() . " WHERE {$whereSql} ORDER BY rv.id DESC", 'DB');

                return ['success' => true, 'data' => $data ?: []];
            }

            $page   = max(1, $page);
            $limit  = max(1, $limit);
            $offset = ($page - 1) * $limit;

            $total = (int) App\ExecuteScalar("SELECT COUNT(*) {$this->joinSql()} WHERE {$whereSql}", 'DB');
            $data  = App\ExecuteRows(
                $this->selectSql() . " WHERE {$whereSql} ORDER BY rv.id DESC LIMIT {$limit} OFFSET {$offset}",
                'DB'
            );

            $totalChange = (float) App\ExecuteScalar(
                "SELECT COALESCE(SUM(rv.to_amount - rv.from_amount), 0) {$this->joinSql()} WHERE {$whereSql}",
                'DB'
            );

            return [
                'success'      => true,
                'data'         => $data ?: [],
                'total_change' => $totalChange,
                'pagination'   => [
                    'total'        => $total,
                    'per_page'     => $limit,
                    'current_page' => $page,
                    'last_page'    => (int) ceil($total / $limit),
                ],
            ];
        } catch (\Exception $e) {
            return $this->failure($e);
        }
    }

    public function fetchById(int|string $id): array
    {
        try {
            $id   = (int) $id;
            $data = App\ExecuteRow($this->selectSql() . " WHERE rv.id = {$id} AND rv.deleted_at IS NULL", 'DB');

            if (!$data) {
                return ['success' => false, 'message' => "Budget revision request #{$id} not found."];
            }

            return ['success' => true, 'data' => $data];
        } catch (\Exception $e) {
            return $this->failure($e);
        }
    }

    public function create(array $body): array
    {
        try {
            // The filing user is whoever is logged in (from the session / JWT), never the request body.
            $userId = App\CurrentUserID();

            $fromId     = $this->parseId($body['from_budget_line_item_id'] ?? null);
            $fromAmount = $body['from_amount'] ?? '';
            $toAmount   = $body['to_amount'] ?? '';

            if ($fromId === null || $fromId === false) {
                return ['success' => false, 'message' => 'from_budget_line_item_id is required.'];
            }
            if (!$this->isAmount($fromAmount) || !$this->isAmount($toAmount)) {
                return ['success' => false, 'message' => 'from_amount and to_amount must be non-negative numbers.'];
            }
            if (!$this->lineExists($fromId)) {
                return ['success' => false, 'message' => "Budget line #{$fromId} does not exist."];
            }
            // optional To line: when set, the revision moves funds from the From line to it
            $toId = $this->parseId($body['to_budget_line_item_id'] ?? null);
            if ($toId === false) {
                return ['success' => false, 'message' => 'to_budget_line_item_id does not exist.'];
            }
            $error = $this->typeError($body['request_type'] ?? null, $toId);
            if ($error !== null) {
                return ['success' => false, 'message' => $error];
            }
            if ($toId !== null) {
                $error = $this->transferError($fromId, $toId, $fromAmount, $toAmount);
                if ($error !== null) {
                    return ['success' => false, 'message' => $error];
                }
            }
            // the From line may not be left with a negative balance
            $error = $this->fromBalanceError($fromId, $toAmount);
            if ($error !== null) {
                return ['success' => false, 'message' => $error];
            }
            // PHPMaker gives the built-in administrator (superadmin) the id -1, so a negative id
            // is a valid user. Only an empty / non-numeric / 0 id means nobody is logged in.
            if (!is_numeric($userId) || (int) $userId === 0) {
                return ['success' => false, 'message' => 'Unable to determine the current user.'];
            }
            // a new revision starts as Saved — still editable, and not yet in front of the reviewers; process() submits it
            // (looked up first: when the status is missing nothing is written)
            $savedId = $this->statusId(self::STATUS_SAVED);
            if ($savedId === null) {
                return $this->missingStatus(self::STATUS_SAVED);
            }

            $sql = "INSERT INTO {$this->table} (request_type, from_budget_line_item_id, to_budget_line_item_id, from_amount, to_amount, reason, user_id, status_id)
                    VALUES ("
                . App\QuotedValue($this->typeFor($toId), App\DataType::STRING, 'DB') . ', '
                . App\QuotedValue($fromId, App\DataType::NUMBER, 'DB') . ', '
                . ($toId === null ? 'NULL' : App\QuotedValue($toId, App\DataType::NUMBER, 'DB')) . ', '
                . App\QuotedValue($fromAmount, App\DataType::NUMBER, 'DB') . ', '
                . App\QuotedValue($toAmount, App\DataType::NUMBER, 'DB') . ', '
                . $this->reasonSql($body) . ', '
                . App\QuotedValue((int) $userId, App\DataType::NUMBER, 'DB') . ', '
                . $savedId . ')
                    RETURNING id';

            $row = App\ExecuteRow($sql, 'DB');

            return [
                'success' => true,
                'message' => 'Budget revision request saved. Choose Process to submit it for review.',
                'id'      => $row['id'] ?? null,
                'status'  => 'SAVED',
            ];
        } catch (\Exception $e) {
            return $this->failure($e);
        }
    }

    public function update(int|string $id, array $body): array
    {
        try {
            $check = $this->fetchById($id);
            if (!$check['success']) {
                return $check;
            }

            // Only a SAVED request can be edited. Once it is processed (Submitted) it is in front of the reviewers, and an
            // approved one has already been applied to its lines' adjustments — changing either afterwards would leave the
            // request and what was reviewed / applied out of step. (A declined one is final too.)
            if (($check['data']['status'] ?? '') !== 'SAVED') {
                $current = strtolower((string) ($check['data']['status'] ?? ''));

                return ['success' => false, 'message' => "Budget revision request #{$id} is {$current} and can no longer be edited — only a saved request can be."];
            }

            $setParts = [];

            // The values the revision will have after this update (the stored ones unless the
            // body changes them) — the From/To line rule below is checked against these.
            $row     = $check['data'];
            $fromId  = $row['from_budget_line_item_id'] === null ? null : (int) $row['from_budget_line_item_id'];
            $toId    = $row['to_budget_line_item_id'] === null ? null : (int) $row['to_budget_line_item_id'];
            $fromAmt = $row['from_amount'];
            $toAmt   = $row['to_amount'];

            $newFrom = $this->parseId($body['from_budget_line_item_id'] ?? null);
            if ($newFrom === false || ($newFrom !== null && !$this->lineExists($newFrom))) {
                return ['success' => false, 'message' => 'from_budget_line_item_id does not exist.'];
            }
            if ($newFrom !== null) {
                $fromId     = $newFrom;
                $setParts[] = 'from_budget_line_item_id = ' . App\QuotedValue($newFrom, App\DataType::NUMBER, 'DB');
            }

            // The To line can be cleared, so it is applied whenever the key is sent ('' = none).
            if (array_key_exists('to_budget_line_item_id', $body)) {
                $toId = $this->parseId($body['to_budget_line_item_id']);
                if ($toId === false) {
                    return ['success' => false, 'message' => 'to_budget_line_item_id does not exist.'];
                }
                $setParts[] = 'to_budget_line_item_id = ' . ($toId === null ? 'NULL' : App\QuotedValue($toId, App\DataType::NUMBER, 'DB'));
                // the type follows the To line, in the same UPDATE: dropping the To line makes it a REVISION, adding one a REALIGNMENT
                $setParts[] = 'request_type = ' . App\QuotedValue($this->typeFor($toId), App\DataType::STRING, 'DB');
            }

            foreach (['from_amount', 'to_amount'] as $field) {
                $value = $body[$field] ?? null;
                if ($value === null || $value === '') {
                    continue;
                }
                if (!$this->isAmount($value)) {
                    return ['success' => false, 'message' => "{$field} must be a non-negative number."];
                }
                if ($field === 'from_amount') {
                    $fromAmt = $value;
                } else {
                    $toAmt = $value;
                }
                $setParts[] = "{$field} = " . App\QuotedValue($value, App\DataType::NUMBER, 'DB');
            }

            // A revision filed before budget lines were revised has no From line; it can be edited only by giving it one.
            if ($fromId === null) {
                return ['success' => false, 'message' => 'from_budget_line_item_id is required: this revision was filed before budget lines could be revised, so pick its budget line.'];
            }
            $error = $this->typeError($body['request_type'] ?? null, $toId);
            if ($error !== null) {
                return ['success' => false, 'message' => $error];
            }
            if ($toId !== null) {
                $error = $this->transferError($fromId, $toId, $fromAmt, $toAmt);
                if ($error !== null) {
                    return ['success' => false, 'message' => $error];
                }
            }
            // the From line may not be left with a negative balance
            $error = $this->fromBalanceError($fromId, $toAmt);
            if ($error !== null) {
                return ['success' => false, 'message' => $error];
            }

            // reason can be cleared, so it is applied whenever the key is sent.
            if (array_key_exists('reason', $body)) {
                $setParts[] = 'reason = ' . $this->reasonSql($body);
            }

            if (empty($setParts)) {
                return ['success' => false, 'message' => 'No valid fields provided for update.'];
            }

            $setParts[] = 'update_at = NOW()';

            $sql = "UPDATE {$this->table}
                    SET " . implode(', ', $setParts) . '
                    WHERE id = ' . (int) $id;

            App\Execute($sql, 'DB');

            return ['success' => true, 'message' => 'Budget revision request updated successfully.'];
        } catch (\Exception $e) {
            return $this->failure($e);
        }
    }

    // Process a SAVED revision: submit it for review (Saved -> Submitted). From then on it can no longer be edited (update() refuses
    // anything that is not Saved) and FMD can approve or decline it (review()). The lines can have changed since it was saved, so the
    // same checks as when it is filed are made again against them as they are NOW — a request that no longer holds stays Saved, with the
    // reason, and can be edited. The status_id guard makes the change atomic: a second click (or another user) finds no Saved row.
    public function process(int|string $id): array
    {
        try {
            // looked up first: when one is missing nothing has been read as saved or changed
            $savedId = $this->statusId(self::STATUS_SAVED);
            if ($savedId === null) {
                return $this->missingStatus(self::STATUS_SAVED);
            }
            $submittedId = $this->statusId(self::STATUS_SUBMITTED);
            if ($submittedId === null) {
                return $this->missingStatus(self::STATUS_SUBMITTED);
            }

            $check = $this->fetchById($id);
            if (!$check['success']) {
                return $check;
            }

            $row = $check['data'];
            if (($row['status'] ?? '') !== 'SAVED') {
                $current = strtolower((string) ($row['status'] ?? ''));

                return ['success' => false, 'message' => "Only saved requests can be processed — request #{$id} is already {$current}."];
            }

            $fromId = $row['from_budget_line_item_id'] === null ? null : (int) $row['from_budget_line_item_id'];
            $toId   = $row['to_budget_line_item_id'] === null ? null : (int) $row['to_budget_line_item_id'];
            if ($fromId === null || !$this->lineExists($fromId)) {
                return ['success' => false, 'message' => "The From budget line for request #{$id} is missing — edit the request and pick it, then process it."];
            }
            if ($toId !== null) {
                $error = $this->transferError($fromId, $toId, $row['from_amount'], $row['to_amount']);
                if ($error !== null) {
                    return ['success' => false, 'message' => $error];
                }
            }
            $error = $this->fromBalanceError($fromId, $row['to_amount']);
            if ($error !== null) {
                return ['success' => false, 'message' => $error];
            }

            $affected = App\Execute(
                "UPDATE {$this->table}
                 SET status_id = {$submittedId}, update_at = NOW()
                 WHERE id = " . (int) $id . " AND deleted_at IS NULL AND status_id = {$savedId}",
                'DB'
            );
            if (!$affected) {
                return ['success' => false, 'message' => "Request #{$id} was already processed or changed by someone else."];
            }

            return [
                'success' => true,
                'message' => "Budget revision request #{$id} processed — it is now submitted for review and can no longer be edited.",
                'status'  => 'SUBMITTED',
            ];
        } catch (\Exception $e) {
            return $this->failure($e);
        }
    }

    // Approve or decline a SUBMITTED revision (one that has been processed). $status is 'APPROVED' or 'DECLINED'.
    // DECLINED only records the decision. APPROVED also applies the change to the budget line(s)
    // (their adjustment) — see approve().
    public function review(int|string $id, string $status): array
    {
        try {
            $target = [
                'APPROVED' => self::STATUS_APPROVED,
                'DECLINED' => self::STATUS_DECLINED,
            ][strtoupper(trim($status))] ?? null;

            if ($target === null) {
                return ['success' => false, 'message' => "status must be 'APPROVED' or 'DECLINED'."];
            }

            // The statuses are looked up first: when one is missing nothing has been read as submitted or changed.
            if ($this->statusId(self::STATUS_SUBMITTED) === null) {
                return $this->missingStatus(self::STATUS_SUBMITTED);
            }
            $targetId = $this->statusId($target);
            if ($targetId === null) {
                return $this->missingStatus($target);
            }

            $check = $this->fetchById($id);
            if (!$check['success']) {
                return $check;
            }

            if (($check['data']['status'] ?? '') !== 'SUBMITTED') {
                $current = ucfirst(strtolower((string) $check['data']['status']));

                return ['success' => false, 'message' => "Only submitted requests can be reviewed — request #{$id} is {$current}"
                    . (($check['data']['status'] ?? '') === 'SAVED' ? ': it has to be processed first.' : '.')];
            }

            if ($target === self::STATUS_APPROVED) {
                return $this->approve((int) $id, $check['data']);
            }

            // DECLINED — only the status changes; the budget lines are left alone.
            // The status_id guard makes the change atomic: if someone reviewed it
            // between the read above and this UPDATE, no row matches.
            $affected = App\Execute(
                "UPDATE {$this->table}
                 SET status_id = {$targetId}, update_at = NOW()
                 WHERE id = " . (int) $id . ' AND deleted_at IS NULL AND status_id = ' . $this->statusId(self::STATUS_SUBMITTED),
                'DB'
            );
            if (!$affected) {
                return ['success' => false, 'message' => "Request #{$id} was already reviewed by someone else."];
            }

            return [
                'success' => true,
                'message' => "Budget revision request #{$id} declined.",
                'status'  => 'DECLINED',
            ];
        } catch (\Exception $e) {
            return $this->failure($e);
        }
    }

    // Approve = record the decision AND apply it to the budget line(s), as ONE statement so
    // either everything happens or nothing does. suggested_amount and proposed_amount are NOT touched: the change is written to the ledger
    // fims.budget_line_item_revision_transaction — one row per line, with the signed amount, the previous balance and the new balance — and the line's
    // adjustment (the total) follows by itself: a trigger on the ledger sets each row's running adjustment and the line's adjustment = SUM of its rows. A line's current amount is its remaining balance — its
    // revised amount (suggested_amount + its ledger total) less what CBAs / CFAs hold and RFAs / LAAs have drawn — the "Current balance" the form shows:
    //   From line (from_budget_line_item_id) — always:
    //     ledger row  amount = to_amount − the balance the line has right now (REVISION, or REALIGNMENT_OUT when there is a To line)
    //                 → its balance becomes to_amount
    //   To line (to_budget_line_item_id) — only when the revision has one: it receives what the From line gave up,
    //     ledger row  amount = the From line's current balance − to_amount (REALIGNMENT_IN)
    // so the two move by the same amount in opposite directions. The change is measured against the live amount, not
    // from_amount: from_amount can be stale if another revision was approved after this one was filed.
    // The COB Monitoring sheet's Revision Amount is the sum of those rows (CobService).
    private function approve(int $id, array $rev): array
    {
        $fromId = $rev['from_budget_line_item_id'] === null ? null : (int) $rev['from_budget_line_item_id'];
        $toId   = $rev['to_budget_line_item_id'] === null ? null : (int) $rev['to_budget_line_item_id'];
        $newAmt = round((float) $rev['to_amount'], 2);

        // the ids of the two statuses the approval moves the revision between (review() has already found them)
        $submittedId = $this->statusId(self::STATUS_SUBMITTED);
        $approvedId  = $this->statusId(self::STATUS_APPROVED);
        if ($submittedId === null) {
            return $this->missingStatus(self::STATUS_SUBMITTED);
        }
        if ($approvedId === null) {
            return $this->missingStatus(self::STATUS_APPROVED);
        }

        if ($newAmt >= self::MAX_LINE_AMOUNT) {
            return ['success' => false, 'message' => 'To Amount is too large for a budget line (maximum 9,999,999,999,999.99).'];
        }
        if ($fromId === null || !$this->lineExists($fromId)) {
            return ['success' => false, 'message' => "The From budget line for revision #{$id} no longer exists."];
        }
        // The balance may have dropped since this was filed (CBAs approved against the line in the meantime): re-check it now.
        $balanceError = $this->fromBalanceError($fromId, $newAmt);
        if ($balanceError !== null) {
            return ['success' => false, 'message' => $balanceError];
        }

        $moved = 0.0;
        $toNow = 0.0;
        if ($toId !== null) {
            if ($toId === $fromId) {
                return ['success' => false, 'message' => "Revision #{$id} has the same budget line as its From and To line."];
            }
            if (!$this->lineExists($toId)) {
                return ['success' => false, 'message' => "The To budget line for revision #{$id} no longer exists."];
            }
            // a request filed before the same-year rule could span two fiscal years: it cannot be approved (decline it and file it again)
            $yearError = $this->sameYearError($fromId, $toId);
            if ($yearError !== null) {
                return ['success' => false, 'message' => "Request #{$id} cannot be approved. {$yearError} Decline it and file the realignment again."];
            }
            // a request filed before the same-item rule could move funds between two rows of one budget line item: it cannot be approved either
            $itemError = $this->sameItemError($fromId, $toId);
            if ($itemError !== null) {
                return ['success' => false, 'message' => "Request #{$id} cannot be approved. {$itemError} Decline it and file the realignment again."];
            }
            // What the From line has right now decides how much moves; it must really go down.
            $fromNow = $this->currentAmountOf($fromId);
            $toNow   = $this->currentAmountOf($toId);
            $moved   = round($fromNow - $newAmt, 2);
            if ($moved <= 0) {
                return ['success' => false, 'message' => 'To Amount ' . number_format($newAmt, 2) . ' is not lower than the From budget line\'s current amount '
                    . number_format($fromNow, 2) . ', so no funds can be moved to the To budget line.'];
            }
            if ($toNow + $moved >= self::MAX_LINE_AMOUNT) {
                return ['success' => false, 'message' => 'The To budget line cannot hold that much (maximum 9,999,999,999,999.99).'];
            }
        }

        // The statements below are data-modifying CTEs: they all see the same snapshot, so `moves` reads each line's current amount as it was
        // BEFORE this approval (the ledger rows written below are not in it yet). The WHERE guards in `approved` keep a double approval from
        // applying twice and stop a transfer whose lines changed under us. The ledger's unique index (one row per request and line) is a second
        // lock against applying a request twice.
        $ledger     = BudgetLineBalanceSql::REVISION_LEDGER_TABLE;
        $fromNowSql = BudgetLineBalanceSql::correlatedAvailableExpr('f');
        $toNowSql   = BudgetLineBalanceSql::correlatedAvailableExpr('t');
        $byUser     = (int) App\CurrentUserID();
        $row = App\ExecuteRow(
            "WITH approved AS (
                 UPDATE {$this->table} rv
                 SET status_id = {$approvedId}, update_at = NOW()
                 WHERE rv.id = {$id} AND rv.deleted_at IS NULL AND rv.status_id = {$submittedId}
                   AND EXISTS (SELECT 1 FROM {$this->tableLines} x WHERE x.budget_line_item_id = rv.from_budget_line_item_id)
                   AND rv.to_amount >= 0   -- the From line's remaining balance becomes To Amount: never negative (so never below what CBAs / RFAs / LAAs hold)
                   AND (rv.to_budget_line_item_id IS NULL
                        OR (rv.to_budget_line_item_id <> rv.from_budget_line_item_id
                            AND EXISTS (SELECT 1 FROM {$this->tableLines} t WHERE t.budget_line_item_id = rv.to_budget_line_item_id)
                            AND rv.to_amount < (SELECT " . BudgetLineBalanceSql::correlatedAvailableExpr('g') . " FROM {$this->tableLines} g
                                                WHERE g.budget_line_item_id = rv.from_budget_line_item_id)))
                 RETURNING rv.id AS revision_id, rv.from_budget_line_item_id, rv.to_budget_line_item_id, rv.to_amount
             ),
             moves AS (
                 -- each touched line's current balance (revised amount less what CBAs / RFAs / LAAs hold) before this approval; to_now is NULL when there is no To line
                 SELECT a.revision_id, a.to_amount,
                        a.from_budget_line_item_id AS from_id, a.to_budget_line_item_id AS to_id,
                        {$fromNowSql} AS from_now, {$toNowSql} AS to_now
                 FROM approved a
                 JOIN {$this->tableLines} f ON f.budget_line_item_id = a.from_budget_line_item_id
                 LEFT JOIN {$this->tableLines} t ON t.budget_line_item_id = a.to_budget_line_item_id
             ),
             from_txn AS (
                 -- the From line: amount = To Amount − what it has now, so its new amount is exactly To Amount
                 INSERT INTO {$ledger} (budget_revision_id, budget_line_item_id, transaction_type, previous_amount, amount, new_amount, created_by)
                 SELECT m.revision_id, m.from_id, CASE WHEN m.to_id IS NULL THEN 'REVISION' ELSE 'REALIGNMENT_OUT' END,
                        m.from_now, m.to_amount - m.from_now, m.to_amount, {$byUser}
                 FROM moves m
                 RETURNING transaction_id, budget_line_item_id, amount, new_amount, adjustment
             ),
             to_txn AS (
                 -- the To line (a realignment only): it receives what the From line gave up
                 INSERT INTO {$ledger} (budget_revision_id, budget_line_item_id, transaction_type, previous_amount, amount, new_amount, created_by)
                 SELECT m.revision_id, m.to_id, 'REALIGNMENT_IN',
                        m.to_now, m.from_now - m.to_amount, m.to_now + (m.from_now - m.to_amount), {$byUser}
                 FROM moves m
                 WHERE m.to_id IS NOT NULL
                 RETURNING transaction_id, budget_line_item_id, amount, new_amount, adjustment
             )
             SELECT ft.budget_line_item_id AS from_id, ft.adjustment AS from_adjustment, f.suggested_amount AS from_suggested,
                    ft.transaction_id AS from_transaction_id, ft.amount AS from_transaction_amount,
                    tt.budget_line_item_id AS to_id,   tt.adjustment AS to_adjustment,   t.suggested_amount AS to_suggested,
                    tt.transaction_id AS to_transaction_id, tt.amount AS to_transaction_amount
             FROM from_txn ft
             JOIN {$this->tableLines} f ON f.budget_line_item_id = ft.budget_line_item_id
             LEFT JOIN to_txn tt ON TRUE
             LEFT JOIN {$this->tableLines} t ON t.budget_line_item_id = tt.budget_line_item_id",
            'DB'
        );

        if (!$row) {
            return ['success' => false, 'message' => "Request #{$id} could not be approved — it was already reviewed by someone else, or its budget lines changed in the meantime."];
        }

        $result = [
            'success'     => true,
            'message'     => $toId === null
                ? "Budget revision request #{$id} approved and recorded against the budget line."
                : "Budget revision request #{$id} approved: " . number_format($moved, 2) . ' moved from the From budget line to the To budget line.',
            'status'      => 'APPROVED',
            // the From line: its id, its new current amount, the ledger row written for it (transaction_id, amount), its adjustment (the line's running
            // total after this transaction, as the ledger row holds it) and its suggested amount (unchanged)
            'budget_line' => ['budget_line_item_id' => (int) $row['from_id'], 'amount' => $newAmt, 'transaction_id' => (int) $row['from_transaction_id'], 'transaction_amount' => $row['from_transaction_amount'],
                              'adjustment' => $row['from_adjustment'], 'suggested_amount' => $row['from_suggested']],
        ];
        if ($row['to_id'] !== null) {
            $result['to_budget_line'] = ['budget_line_item_id' => (int) $row['to_id'], 'amount' => round($toNow + $moved, 2), 'transaction_id' => (int) $row['to_transaction_id'], 'transaction_amount' => $row['to_transaction_amount'],
                                         'adjustment' => $row['to_adjustment'], 'suggested_amount' => $row['to_suggested']];
        }

        // the approval is committed: tell the offices whose budget just changed (can never fail it)
        $result['notified'] = $this->notifyApproved($id, $rev, $fromId, $toId, $newAmt, $moved);

        return $result;
    }

    // The rc_id of the budget request(s) the given budget lines belong to (fims.budget_req.rc_id — the originating office), each once.
    private function budgetRcIdsOf(array $lineIds): array
    {
        $ids = array_values(array_unique(array_filter(array_map('intval', $lineIds), fn ($v) => $v > 0)));
        if (!$ids) {
            return [];
        }
        $rows = App\ExecuteRows(
            "SELECT DISTINCT b.rc_id FROM {$this->tableLines} l
               JOIN {$this->tableReq} b ON b.budget_reference_number = l.budget_reference_number
              WHERE l.budget_line_item_id IN (" . implode(', ', $ids) . ")
                AND b.rc_id IS NOT NULL AND TRIM(b.rc_id) <> ''",
            'DB'
        ) ?: [];

        return array_values(array_unique(array_map(fn ($r) => trim((string) $r['rc_id']), $rows)));
    }

    // "5-02-010 — Travelling Expenses (BP-001)" for the notification text; $pre is '' for the From line, 'to_' for the To line.
    private function lineLabel(array $rev, string $pre, int $lineId): string
    {
        $code  = trim((string) ($rev[$pre . 'account_code'] ?? ''));
        $title = trim((string) ($rev[$pre . 'account_title'] ?? ''));
        $ref   = trim((string) ($rev[$pre . 'budget_reference_number'] ?? ''));
        $name  = $code !== '' ? $code . ($title !== '' ? ' — ' . $title : '') : "budget line #{$lineId}";

        return $ref !== '' ? "{$name} ({$ref})" : $name;
    }

    // Where a click on the notification goes: the Budget Requirements page (route BudgetReqPage), which then opens "View as COB" for the
    // fiscal year (budget-req-page.php reads open=cob and fy). GetUrl() adds the app's base path (it may live in a sub-folder); the hub only
    // accepts a link that starts with "/", so one is added when the base path is empty.
    // NOT "view": that is a reserved PHPMaker query parameter (Config("VIEW")) — every page class reads it as the name of a template to
    // render, so ?view=cob made the framework look for "cob.php" and fail before the page ever loaded. Any new parameter name here must not be one
    // the framework reserves (see the "TABLE_*", "PAGE_*", "VIEW", "API_*" names in src/config.php).
    private function budgetReqPageLink(?int $fiscalYr): string
    {
        $path = 'BudgetReqPage?open=cob' . ($fiscalYr ? '&fy=' . $fiscalYr : '');
        try {
            $link = (string) App\GetUrl($path);
        } catch (\Throwable $e) {
            $link = $path;
        }

        return '/' . ltrim($link, '/');
    }

    // An approved revision / realignment changes an office's budget, so that office is told: every active user whose uac.users.rc_id is the
    // rc_id of a budget request it touched — the From line's request, and (a realignment) the To line's, which may be another office's.
    // Sent once per office and person (event_key), never to the reviewer. Never throws; returns how many people were notified.
    private function notifyApproved(int $id, array $rev, int $fromId, ?int $toId, float $newAmt, float $moved): int
    {
        try {
            $rcIds = $this->budgetRcIdsOf([$fromId, $toId]);
            if (!$rcIds) {
                return 0;
            }

            $fromName = $this->lineLabel($rev, '', $fromId);
            if ($toId === null) {
                $subject = 'Budget revision approved';
                $body    = "Request #{$id}: {$fromName} was changed from ₱" . number_format((float) ($rev['line_amount'] ?? 0), 2)
                    . ' to ₱' . number_format($newAmt, 2) . '.';
            } else {
                $subject = 'Budget realignment approved';
                $body    = "Request #{$id}: ₱" . number_format($moved, 2) . " was moved from {$fromName} to " . $this->lineLabel($rev, 'to_', $toId) . '.';
            }

            $year   = $rev['fiscal_yr'] ?? null;
            $link   = $this->budgetReqPageLink(is_numeric($year) ? (int) $year : null);
            $sender = (int) App\CurrentUserID();

            $count = 0;
            foreach ($rcIds as $rc) {
                $count += NotificationService::toRc($rc, $subject, $body, $link, [
                    'sender_id' => $sender > 0 ? $sender : null,
                    'event_key' => "budget_revision_approved:{$id}:{$rc}",
                ]);
            }

            return $count;
        } catch (\Throwable $e) {
            App\LogError("BudgetRevisionService: could not notify for revision #{$id} — " . $e->getMessage());

            return 0;
        }
    }

    // Soft delete — the table carries deleted_at, so the row is kept.
    public function delete(int|string $id): array
    {
        try {
            $check = $this->fetchById($id);
            if (!$check['success']) {
                return $check;
            }

            $sql = "UPDATE {$this->table}
                    SET deleted_at = NOW(), update_at = NOW()
                    WHERE id = " . (int) $id;
            App\Execute($sql, 'DB');

            return ['success' => true, 'message' => "Budget revision request #{$id} deleted successfully."];
        } catch (\Exception $e) {
            return $this->failure($e);
        }
    }
