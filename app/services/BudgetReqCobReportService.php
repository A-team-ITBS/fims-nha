<?php

namespace PHPMaker2024\FIMS\Service;

use PHPMaker2024\FIMS as App;
use PHPMaker2024\FIMS\DataType;

/**
 * Budget Request "Print COB" -> "Per Region" / "Per Program": a real .xlsx for each, built from the budget_req /
 * budget_line_items tables directly (the SAME source readone/budget-req-readone.php's "View as COB" modal reads
 * via BGR_API + '/all') — NOT CobService's Approved-only COB Monitoring data, since "Print COB" here runs from the
 * Budget Request / Budget Proposal list on whatever requests exist, any status, same as the on-screen modal.
 *
 * Both reports share the SAME structural CO vs. COE split and the SAME three money columns; they differ only in
 * what the CAPITAL OUTLAY section groups by and how deep it goes:
 *
 *   "Per Region" (buildRegion/xlsxRegion) — one rolled-up TOTAL row per Region, not a nested tree. Matches the
 *     supplied "per region.xlsx" template; its own huge Program/Sub-Program/Project breakdown per region is NOT
 *     reproduced — see buildRegion()'s own doc comment.
 *   "Per Program" (buildProgram/xlsxProgram) — the full tree: one row per Program, one per Sub-Program under it,
 *     one per Project under that, each indented one level deeper. Matches the supplied "per project.xlsx"
 *     template's row order/labels — its own "AVAILABLE BUDGET" column and its PROGRAM/SUB-PROGRAM/PROJECT rows'
 *     literal text are NOT reproduced: those three rows are read as a style guide for the indentation the real,
 *     dynamic rows below them should use, not as data of their own. No region axis at all — scoped directly by
 *     $scopeRcId, same as everything else here.
 *
 * CO vs. COE: budget_line_items.budget_req_project_id IS NOT NULL (tied to a Project) = CO, IS NULL (headless) =
 * COE — the SAME structural rule BudgetReqService itself uses to split a header's lines into its programs/projects
 * vs. its headless coe_line_items — NOT an account-code prefix (that's CobService's own rule, for a different,
 * Approved-only COB Monitoring dataset; conflating the two under-counts every CO line whose account code doesn't
 * happen to start with '1'). The account-code prefix IS used, correctly, for the Personnel Services / MOOE
 * sub-split WITHIN the already-headless COE lines (coeBreakdown()) — same rule bgrv_deriveExpenseClass() uses for
 * that same purpose on the "View as COB" modal; a COE line matching neither prefix still counts toward the COE
 * total, just not its own Personnel Services / MOOE row — same as that modal's own behaviour.
 *
 * Three money columns per row, both reports:
 *   Proposed  budget_line_items.proposed_amount  — the office's own original ask
 *   Approved  budget_line_items.suggested_amount — Budget Processing's figure (0 until Endorsed; STABLE afterwards
 *             — see BudgetLineBalanceSql's class doc — no CBA/RFA/LAA or Budget Revision ever moves it again)
 *   Amended   budget_line_items.revised_amount   — GENERATED by the table as suggested_amount + adjustment
 *             ("54 - budget_line_items_revised_amount_generated.sql")
 * These are the same three figures the "View as COB" modal shows (bgrv_cobCollect's proposed/adjustment/revised),
 * just without that modal's old "suggested, else proposed" display fallback (bgrv_approvedAmount, since removed) —
 * Approved here is exactly suggested_amount, 0 when Budget Processing has not endorsed yet.
 */
class BudgetReqCobReportService
{
    private string $tableBudgetReq = 'fims.budget_req';
    private string $tableLineItems = 'fims.budget_line_items';
    private string $tableBudgetReqProgram = 'fims.budget_req_program';
    private string $tableBudgetReqProject = 'fims.budget_req_project';
    private string $tableProgram = 'fims.program';
    private string $tableSubProgram = 'fims.sub_program';
    private string $tableProject = 'fims.project';

    /** Header fill (RGB, no '#') — the same navy CobReportService::xlsx() uses, for a consistent look across the app's Excel exports. */
    private const HEAD = '1F497D';
    private const TOTAL_FILL = 'D9D9D9';
    private const LINE = 'D9D9D9';
    private const NUM_FMT = '#,##0.00;(#,##0.00);"-"';

    private static function str(string $v): string
    {
        return App\QuotedValue($v, DataType::STRING, 'DB');
    }

    /** @param string[] $ids */
    private static function inList(array $ids): string
    {
        return implode(', ', array_map(fn ($id) => self::str((string) $id), $ids ?: ['']));
    }

    /** One SUM() row's three amounts, cast to float — proposed/approved/amended. */
    private static function amt(array $row): array
    {
        return ['proposed' => (float) $row['proposed'], 'approved' => (float) $row['approved'], 'amended' => (float) $row['amended']];
    }

    private static function zero(): array
    {
        return ['proposed' => 0.0, 'approved' => 0.0, 'amended' => 0.0];
    }

    // -------------------------------------------------------------------------
    // Shared: Corporate Operating Expenditure (same for both reports)
    // -------------------------------------------------------------------------

    /**
     * Every headless line (budget_req_project_id IS NULL), sub-classified PS ('5-01…') / MOOE ('5-02…') by
     * account code. $fyWhere / $scopeWhere are the already-built ' AND br.xxx = …' fragments (possibly '').
     *
     * @return array{ps: array, mooe: array, total: array}
     */
    private function coeBreakdown(string $fyWhere, string $scopeWhere): array
    {
        $rows = App\ExecuteRows(
            "SELECT CASE WHEN coa.account_code LIKE '5-01%' THEN 'PS' WHEN coa.account_code LIKE '5-02%' THEN 'MOOE' ELSE 'OTHER' END AS cls,
                    COALESCE(SUM(li.proposed_amount), 0) AS proposed,
                    COALESCE(SUM(li.suggested_amount), 0) AS approved,
                    COALESCE(SUM(li.revised_amount), 0) AS amended
             FROM {$this->tableLineItems} li
             JOIN {$this->tableBudgetReq} br ON br.budget_reference_number = li.budget_reference_number
             LEFT JOIN fims.chart_of_accounts coa ON coa.account_id = li.account_id
             WHERE li.budget_req_project_id IS NULL{$fyWhere}{$scopeWhere}
             GROUP BY CASE WHEN coa.account_code LIKE '5-01%' THEN 'PS' WHEN coa.account_code LIKE '5-02%' THEN 'MOOE' ELSE 'OTHER' END",
            'DB'
        ) ?: [];

        $ps = self::zero();
        $mooe = self::zero();
        $total = self::zero();
        foreach ($rows as $row) {
            $a = self::amt($row);
            if ($row['cls'] === 'PS') {
                $ps = $a;
            } elseif ($row['cls'] === 'MOOE') {
                $mooe = $a;
            }
            foreach (['proposed', 'approved', 'amended'] as $k) {
                $total[$k] += $a[$k];
            }
        }

        return ['ps' => $ps, 'mooe' => $mooe, 'total' => $total];
    }

    // -------------------------------------------------------------------------
    // Per Region — model
    // -------------------------------------------------------------------------

    /**
     * @param string $fiscalYr '' = every fiscal year
     * @param string $scopeRcId the RC the caller is limited to ('' = every RC), as resolved by
     *                          GlobalService::resolveBudgetReqRcFilter() — same convention as /budget_req/all
     *
     * @return array{success: bool, data?: array, httpCode?: int, message?: string}
     */
    public function buildRegion(string $fiscalYr = '', string $scopeRcId = ''): array
    {
        try {
            $fy = trim($fiscalYr) !== '' ? (int) $fiscalYr : null;
            $scopeIds = trim($scopeRcId) !== '' ? (GlobalService::getRcIdsInScope($scopeRcId) ?: [$scopeRcId]) : null;

            $fyWhere = $fy !== null ? ' AND br.fiscal_yr = '.$fy : '';
            $scopeWhere = $scopeIds !== null ? ' AND br.rc_id IN ('.self::inList($scopeIds).')' : '';

            // Every Regional office the caller may see, rc_code order — the row labels of the CAPITAL OUTLAY section.
            $regionWhere = "WHERE office_type = 'Regional'".($scopeIds !== null ? ' AND rc_id IN ('.self::inList($scopeIds).')' : '');
            $regions = App\ExecuteRows(
                "SELECT rc_id, rc_name, rc_code FROM fims.responsibility_code {$regionWhere} ORDER BY rc_code ASC NULLS LAST, rc_name ASC",
                'DB'
            ) ?: [];

            // CO line items, rolled up by the Region each requesting office belongs to: a Region's own requests
            // PLUS every descendant office's (its Districts, via parent_rc_id — any depth), via a recursive walk
            // DOWN from each Regional office — the same descendant-closure idea as GlobalService::getRcIdsInScope(),
            // just for every Region at once.
            $coRows = App\ExecuteRows(
                "WITH RECURSIVE region_tree AS (
                    SELECT rc_id AS region_id, rc_id FROM fims.responsibility_code WHERE office_type = 'Regional'
                    UNION ALL
                    SELECT rt.region_id, child.rc_id
                    FROM fims.responsibility_code child
                    JOIN region_tree rt ON child.parent_rc_id = rt.rc_id
                 )
                 SELECT rt.region_id,
                        COALESCE(SUM(li.proposed_amount), 0) AS proposed,
                        COALESCE(SUM(li.suggested_amount), 0) AS approved,
                        COALESCE(SUM(li.revised_amount), 0) AS amended
                 FROM region_tree rt
                 JOIN {$this->tableBudgetReq} br ON br.rc_id = rt.rc_id
                 JOIN {$this->tableLineItems} li ON li.budget_reference_number = br.budget_reference_number
                 WHERE li.budget_req_project_id IS NOT NULL{$fyWhere}
                 GROUP BY rt.region_id",
                'DB'
            ) ?: [];
            $coByRegion = [];
            foreach ($coRows as $row) {
                $coByRegion[(string) $row['region_id']] = self::amt($row);
            }

            $regionRows = [];
            $coTotal = self::zero();
            foreach ($regions as $rg) {
                $a = $coByRegion[(string) $rg['rc_id']] ?? self::zero();
                $regionRows[] = ['label' => (string) $rg['rc_name']] + $a;
                foreach (['proposed', 'approved', 'amended'] as $k) {
                    $coTotal[$k] += $a[$k];
                }
            }

            $coe = $this->coeBreakdown($fyWhere, $scopeWhere);
            $grand = [
                'proposed' => $coTotal['proposed'] + $coe['total']['proposed'],
                'approved' => $coTotal['approved'] + $coe['total']['approved'],
                'amended' => $coTotal['amended'] + $coe['total']['amended'],
            ];

            return ['success' => true, 'data' => [
                'fiscal_yr' => $fy,
                'generated' => date('F j, Y'),
                'grand' => $grand,
                'co_total' => $coTotal,
                'coe_total' => $coe['total'],
                'regions' => $regionRows,
                'ps' => $coe['ps'],
                'mooe' => $coe['mooe'],
            ]];
        } catch (\Throwable $e) {
            App\LogError('BudgetReqCobReportService::buildRegion '.$e->getMessage());

            return ['success' => false, 'httpCode' => 500, 'message' => 'Failed to build the Per Region report.'];
        }
    }

    /** The one "Print COB" entry point both report modes go through — see MODES below. */
    private const MODES = [
        'region' => ['label' => 'Per Region', 'build' => 'buildRegion', 'xlsx' => 'xlsxRegion'],
        'program' => ['label' => 'Per Program', 'build' => 'buildProgram', 'xlsx' => 'xlsxProgram'],
    ];

    /**
     * @param string $mode 'region' or 'program' — see MODES above
     *
     * @return array{success: bool, filename?: string, mime?: string, data?: string, httpCode?: int, message?: string}
     */
    public function report(string $mode, string $fiscalYr = '', string $scopeRcId = ''): array
    {
        if (!isset(self::MODES[$mode])) {
            return ['success' => false, 'httpCode' => 400, 'message' => 'mode must be one of: '.implode(', ', array_keys(self::MODES))];
        }
        $cfg = self::MODES[$mode];

        $built = $this->{$cfg['build']}($fiscalYr, $scopeRcId);
        if (!$built['success']) {
            return $built;
        }
        $m = $built['data'];
        $name = 'Budget_Req_'.str_replace(' ', '_', $cfg['label']).($m['fiscal_yr'] !== null ? '_FY'.$m['fiscal_yr'] : '').'_'.date('Ymd').'.xlsx';

        try {
            return ['success' => true, 'filename' => $name, 'mime' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
                'data' => base64_encode($this->{$cfg['xlsx']}($m))];
        } catch (\Throwable $e) {
            App\LogError('BudgetReqCobReportService::report '.$mode.' '.$e->getMessage());

            return ['success' => false, 'httpCode' => 500, 'message' => 'The '.$cfg['label'].' report could not be generated.'];
        }
    }

    /**
     * The workbook: date + the three amount headers, the Region/Program/Project label, a couple of spacer rows, TOTAL,
     * CAPITAL OUTLAY (+ one row per Region), CORPORATE OPERATING EXPENDITURE (+ Personnel Services / MOOE). A zero cell
     * shows as "-", a negative in brackets — Excel's own number format, not a PHP-formatted string, so the cell still
     * keeps its full value.
     */
    public function xlsxRegion(array $m): string
    {
        $x = new XlsxWriter('Per Region');
        [$s, $amountRow] = $this->xlsxCommon($x);

        $s['label'] = $x->style(['font' => $this->font(), 'border' => self::LINE, 'align' => ['h' => 'left', 'v' => 'center', 'indent' => 1]]);
        $s['labelChild'] = $x->style(['font' => $this->font(), 'border' => self::LINE, 'align' => ['h' => 'left', 'v' => 'center', 'indent' => 2]]);
        $s['num'] = $x->style(['font' => $this->font(), 'border' => self::LINE, 'align' => ['h' => 'right', 'v' => 'center'], 'numFmt' => self::NUM_FMT]);

        $r = $this->xlsxHeader($x, $m, $s);

        $amountRow($r, 'TOTAL', $m['grand'], $s['totalLabel'], $s['totalNum']);
        $amountRow($r, 'CAPITAL OUTLAY', $m['co_total'], $s['labelBold'], $s['numBold']);
        foreach ($m['regions'] as $rg) {
            $amountRow($r, $rg['label'], $rg, $s['label'], $s['num']);
        }
        $amountRow($r, 'CORPORATE OPERATING EXPENDITURE', $m['coe_total'], $s['labelBold'], $s['numBold']);
        $amountRow($r, 'Personnel Services', $m['ps'], $s['labelChild'], $s['num']);
        $amountRow($r, 'MOOE', $m['mooe'], $s['labelChild'], $s['num']);

        $this->xlsxColWidths($x, 48);

        return $x->render();
    }

    // -------------------------------------------------------------------------
    // Per Program — model
    // -------------------------------------------------------------------------

    /**
     * @param string $fiscalYr '' = every fiscal year
     * @param string $scopeRcId the RC the caller is limited to ('' = every RC) — same convention as buildRegion()
     *
     * @return array{success: bool, data?: array, httpCode?: int, message?: string}
     */
    public function buildProgram(string $fiscalYr = '', string $scopeRcId = ''): array
    {
        try {
            $fy = trim($fiscalYr) !== '' ? (int) $fiscalYr : null;
            $scopeIds = trim($scopeRcId) !== '' ? (GlobalService::getRcIdsInScope($scopeRcId) ?: [$scopeRcId]) : null;

            $fyWhere = $fy !== null ? ' AND br.fiscal_yr = '.$fy : '';
            $scopeWhere = $scopeIds !== null ? ' AND br.rc_id IN ('.self::inList($scopeIds).')' : '';

            // CO line items, one row per (Program, Sub-Program, Project) — sub_program_code lives on
            // budget_req_program (a program+sub-program PAIR, not a further-nested table), so the Program /
            // Sub-Program levels come straight off that one row, grouped.
            $rows = App\ExecuteRows(
                "SELECT brp.program_code, pg.program_name,
                        brp.sub_program_code, sp.sub_program_name,
                        bprj.project_code, pj.project_name,
                        COALESCE(SUM(li.proposed_amount), 0) AS proposed,
                        COALESCE(SUM(li.suggested_amount), 0) AS approved,
                        COALESCE(SUM(li.revised_amount), 0) AS amended
                 FROM {$this->tableLineItems} li
                 JOIN {$this->tableBudgetReqProject} bprj ON bprj.budget_req_project_id = li.budget_req_project_id
                 JOIN {$this->tableBudgetReqProgram} brp ON brp.budget_req_program_id = bprj.budget_req_program_id
                 JOIN {$this->tableBudgetReq} br ON br.budget_reference_number = brp.budget_reference_number
                 LEFT JOIN {$this->tableProgram} pg ON pg.program_code = brp.program_code
                 LEFT JOIN {$this->tableSubProgram} sp ON sp.sub_program_code = brp.sub_program_code
                 LEFT JOIN {$this->tableProject} pj ON pj.project_code = bprj.project_code
                 WHERE li.budget_req_project_id IS NOT NULL{$fyWhere}{$scopeWhere}
                 GROUP BY brp.program_code, pg.program_name, brp.sub_program_code, sp.sub_program_name, bprj.project_code, pj.project_name
                 ORDER BY brp.program_code ASC NULLS LAST, brp.sub_program_code ASC NULLS LAST, bprj.project_code ASC NULLS LAST",
                'DB'
            ) ?: [];

            // Flat rows -> nested Program -> Sub-Program -> Project tree, keyed by code while building (so the same
            // Program/Sub-Program recurs across several rows without duplicating its own row), flattened to plain
            // lists below — PHP's own array order preserves the SQL's ORDER BY.
            $programs = [];
            foreach ($rows as $row) {
                $progCode = (string) ($row['program_code'] ?? '');
                $subCode = (string) ($row['sub_program_code'] ?? '');
                $amt = self::amt($row);

                if (!isset($programs[$progCode])) {
                    $programs[$progCode] = [
                        'label' => (string) ($row['program_name'] ?: ($progCode !== '' ? $progCode : 'No Program')),
                    ] + self::zero() + ['subPrograms' => []];
                }
                if (!isset($programs[$progCode]['subPrograms'][$subCode])) {
                    $programs[$progCode]['subPrograms'][$subCode] = [
                        'label' => (string) ($row['sub_program_name'] ?: ($subCode !== '' ? $subCode : 'No Sub-Program')),
                    ] + self::zero() + ['projects' => []];
                }
                $programs[$progCode]['subPrograms'][$subCode]['projects'][] = [
                    'label' => (string) ($row['project_name'] ?: ((string) ($row['project_code'] ?? '') !== '' ? $row['project_code'] : 'Untitled Project')),
                ] + $amt;

                foreach (['proposed', 'approved', 'amended'] as $k) {
                    $programs[$progCode][$k] += $amt[$k];
                    $programs[$progCode]['subPrograms'][$subCode][$k] += $amt[$k];
                }
            }

            $programRows = [];
            $coTotal = self::zero();
            foreach ($programs as $p) {
                $p['subPrograms'] = array_values($p['subPrograms']);
                $programRows[] = $p;
                foreach (['proposed', 'approved', 'amended'] as $k) {
                    $coTotal[$k] += $p[$k];
                }
            }

            $coe = $this->coeBreakdown($fyWhere, $scopeWhere);
            $grand = [
                'proposed' => $coTotal['proposed'] + $coe['total']['proposed'],
                'approved' => $coTotal['approved'] + $coe['total']['approved'],
                'amended' => $coTotal['amended'] + $coe['total']['amended'],
            ];

            return ['success' => true, 'data' => [
                'fiscal_yr' => $fy,
                'generated' => date('F j, Y'),
                'grand' => $grand,
                'co_total' => $coTotal,
                'coe_total' => $coe['total'],
                'programs' => $programRows,
                'ps' => $coe['ps'],
                'mooe' => $coe['mooe'],
            ]];
        } catch (\Throwable $e) {
            App\LogError('BudgetReqCobReportService::buildProgram '.$e->getMessage());

            return ['success' => false, 'httpCode' => 500, 'message' => 'Failed to build the Per Program report.'];
        }
    }

    /**
     * The workbook: date + the three amount headers, the Region/Program/Project label, a couple of spacer rows,
     * TOTAL, CAPITAL OUTLAY (+ Program -> Sub-Program -> Project, each one level deeper), CORPORATE OPERATING
     * EXPENDITURE (+ Personnel Services / MOOE).
     */
    public function xlsxProgram(array $m): string
    {
        $x = new XlsxWriter('Per Program');
        [$s, $amountRow] = $this->xlsxCommon($x);

        // One (label) style per indent level — Program (1) -> Sub-Program (2) -> Project (3); Personnel Services /
        // MOOE reuse level 2's indent, same depth as a Sub-Program. One shared number style for all three (the
        // number format/alignment never changes with depth, only the label's indent does).
        $sLabelLvl = [];
        foreach ([1, 2, 3] as $lvl) {
            $sLabelLvl[$lvl] = $x->style(['font' => $this->font(), 'border' => self::LINE, 'align' => ['h' => 'left', 'v' => 'center', 'indent' => $lvl]]);
        }
        $sNum = $x->style(['font' => $this->font(), 'border' => self::LINE, 'align' => ['h' => 'right', 'v' => 'center'], 'numFmt' => self::NUM_FMT]);

        $r = $this->xlsxHeader($x, $m, $s);

        $amountRow($r, 'TOTAL', $m['grand'], $s['totalLabel'], $s['totalNum']);
        $amountRow($r, 'CAPITAL OUTLAY', $m['co_total'], $s['labelBold'], $s['numBold']);
        foreach ($m['programs'] as $prog) {
            $amountRow($r, $prog['label'], $prog, $sLabelLvl[1], $sNum);
            foreach ($prog['subPrograms'] as $sub) {
                $amountRow($r, $sub['label'], $sub, $sLabelLvl[2], $sNum);
                foreach ($sub['projects'] as $proj) {
                    $amountRow($r, $proj['label'], $proj, $sLabelLvl[3], $sNum);
                }
            }
        }
        $amountRow($r, 'CORPORATE OPERATING EXPENDITURE', $m['coe_total'], $s['labelBold'], $s['numBold']);
        $amountRow($r, 'Personnel Services', $m['ps'], $sLabelLvl[2], $sNum);
        $amountRow($r, 'MOOE', $m['mooe'], $sLabelLvl[2], $sNum);

        $this->xlsxColWidths($x, 60);

        return $x->render();
    }

    // -------------------------------------------------------------------------
    // Shared xlsx() plumbing
    // -------------------------------------------------------------------------

    private function font(array $o = []): array
    {
        return array_merge(['name' => 'Arial', 'sz' => 10], $o);
    }

    /**
     * The styles every "Print COB" export shares, plus the amountRow() closure both xlsxRegion()/xlsxProgram()
     * call to write one (label, proposed, approved, amended) row and advance the row cursor.
     *
     * @return array{0: array<string,int>, 1: \Closure}
     */
    private function xlsxCommon(XlsxWriter $x): array
    {
        $s = [
            'date' => $x->style(['font' => $this->font(['bold' => true, 'color' => self::HEAD])]),
            'th' => $x->style(['font' => $this->font(['bold' => true, 'color' => 'FFFFFF']), 'fill' => self::HEAD, 'border' => 'FFFFFF',
                'align' => ['h' => 'center', 'v' => 'center', 'wrap' => true]]),
            'labelHead' => $x->style(['font' => $this->font(['bold' => true]), 'border' => self::LINE, 'align' => ['h' => 'left', 'v' => 'center', 'wrap' => true]]),
            'labelBold' => $x->style(['font' => $this->font(['bold' => true]), 'border' => self::LINE, 'align' => ['h' => 'left', 'v' => 'center']]),
            'numBold' => $x->style(['font' => $this->font(['bold' => true]), 'border' => self::LINE, 'align' => ['h' => 'right', 'v' => 'center'], 'numFmt' => self::NUM_FMT]),
        ];
        $totalBase = ['font' => $this->font(['bold' => true]), 'fill' => self::TOTAL_FILL, 'border' => self::LINE];
        $s['totalLabel'] = $x->style($totalBase + ['align' => ['h' => 'left', 'v' => 'center']]);
        $s['totalNum'] = $x->style($totalBase + ['align' => ['h' => 'right', 'v' => 'center'], 'numFmt' => self::NUM_FMT]);

        $amountRow = function (int &$r, string $label, array $a, int $labelStyle, int $numStyle) use ($x): void {
            $x->set($r, 0, $label, $labelStyle);
            $x->set($r, 1, $a['proposed'], $numStyle);
            $x->set($r, 2, $a['approved'], $numStyle);
            $x->set($r, 3, $a['amended'], $numStyle);
            $r++;
        };

        return [$s, $amountRow];
    }

    /** Date (col A) + the three amount headers, the Region/Program/Project label row, two spacer rows. Returns the next row index. */
    private function xlsxHeader(XlsxWriter $x, array $m, array $s): int
    {
        $r = 0;
        $x->set($r, 0, $m['fiscal_yr'] !== null ? 'FY '.$m['fiscal_yr'].'   |   '.$m['generated'] : 'All Fiscal Years   |   '.$m['generated'], $s['date']);
        $x->set($r, 1, 'PROPOSED AMOUNT', $s['th']);
        $x->set($r, 2, 'APPROVED AMOUNT', $s['th']);
        $x->set($r, 3, 'AMENDED AMOUNT', $s['th']);
        $x->merge($r, 1, $r + 1, 1);
        $x->merge($r, 2, $r + 1, 2);
        $x->merge($r, 3, $r + 1, 3);
        $x->rowHeight($r, 20);
        $r++;

        $x->set($r, 0, "REGION/PROGRAM/PROJECT\nLOCATION (City/Municipality)", $s['labelHead']);
        $x->rowHeight($r, 32);
        $r++;

        $x->rowHeight($r++, 8);   // spacer rows, as in the template
        $x->rowHeight($r++, 8);

