        };

        return [$s, $amountRow];
    }

    /** Date (col A) + the three amount headers, the Region/Program/Project label row, two spacer rows. Returns the next row index. */
    private function xlsxHeader(XlsxWriter $x, array $m, array $s): int
    {
        $r = 0;
        $x->set($r, 0, $m['fiscal_yr'] !== null ? 'FY '.$m['fiscal_yr'].'   |   '.$m['generated'] : 'All Fiscal Years   |   '.$m['generated'], $s['date']);
        $x->set($r, 1, 'PROPOSED AMOUNT', $s['th']);
        $x->set($r, 2, 'APPROVED AMOUNT', $s['th']);
        // TEMP: Amended Amount column hidden for now — uncomment these two lines (together with the
        // amountRow() closure's $a['amended'] write in xlsxCommon()) to restore it.
        // $x->set($r, 3, 'AMENDED AMOUNT', $s['th']);
        // $x->merge($r, 3, $r + 1, 3);
        $x->merge($r, 1, $r + 1, 1);
        $x->merge($r, 2, $r + 1, 2);
        $x->rowHeight($r, 20);
        $r++;

        $x->set($r, 0, "REGION/PROGRAM/PROJECT\nLOCATION (City/Municipality)", $s['labelHead']);
        $x->rowHeight($r, 32);
        $r++;

        $x->rowHeight($r++, 8);   // spacer rows, as in the template
        $x->rowHeight($r++, 8);

        return $r;
    }

