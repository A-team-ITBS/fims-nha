    /**
     * The styles every "Print COB" export shares, plus the amountRow() closure both xlsxRegion()/xlsxProgram()
     * call to write one (label, proposed, approved, amended) row and advance the row cursor.
     *
     * @return array{0: array<string,int>, 1: \Closure}
     */
    private function xlsxCommon(XlsxWriter $x): array
    {
        $s = [
            'date' => $x->style(['font' => $this->font(['bold' => true, 'color' => self::HEAD])]),
            'th' => $x->style(['font' => $this->font(['bold' => true, 'color' => 'FFFFFF']), 'fill' => self::HEAD, 'border' => 'FFFFFF',
                'align' => ['h' => 'center', 'v' => 'center', 'wrap' => true]]),
            'labelHead' => $x->style(['font' => $this->font(['bold' => true]), 'border' => self::LINE, 'align' => ['h' => 'left', 'v' => 'center', 'wrap' => true]]),
            'labelBold' => $x->style(['font' => $this->font(['bold' => true]), 'border' => self::LINE, 'align' => ['h' => 'left', 'v' => 'center']]),
            'numBold' => $x->style(['font' => $this->font(['bold' => true]), 'border' => self::LINE, 'align' => ['h' => 'right', 'v' => 'center'], 'numFmt' => self::NUM_FMT]),
        ];
        $totalBase = ['font' => $this->font(['bold' => true]), 'fill' => self::TOTAL_FILL, 'border' => self::LINE];
        $s['totalLabel'] = $x->style($totalBase + ['align' => ['h' => 'left', 'v' => 'center']]);
        $s['totalNum'] = $x->style($totalBase + ['align' => ['h' => 'right', 'v' => 'center'], 'numFmt' => self::NUM_FMT]);

        $amountRow = function (int &$r, string $label, array $a, int $labelStyle, int $numStyle) use ($x): void {
            $x->set($r, 0, $label, $labelStyle);
            $x->set($r, 1, $a['proposed'], $numStyle);
            $x->set($r, 2, $a['approved'], $numStyle);
            // TEMP: Amended Amount column hidden for now — uncomment this line (together with the
            // "AMENDED AMOUNT" header in xlsxHeader()) to restore it.
            // $x->set($r, 3, $a['amended'], $numStyle);
